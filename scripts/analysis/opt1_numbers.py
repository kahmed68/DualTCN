"""11-16 Option 1 (rn_noprof main): every number quoted in the revised manuscript/letter, from the result files.
Usage: python3 scripts/analysis/opt1_numbers.py > paper_revision/envsoft_r1/framing_review/NUMBERS_OPT1.md
A number quoted twice is computed once: copy from this output only."""
import json, csv, statistics as st, os
R = '/work/hdd/bgte/kahmed2/DualTCN_runs'; E = R + '/e1'; A = R + '/analysis'
P = ['s1', 's2', 'd1', 'd2']; NM = ['sigma1', 'sigma2', 'd1', 'd2']
J = lambda p: json.load(open(p))
f3 = lambda x: f'{x:.3f}'


def test(run):
    return [J(f'{E}/{run}_s{s}/test_metrics.json')['test'] for s in (1, 2, 3)]


def ms(v):
    return st.mean(v), st.stdev(v)


print('# NUMBERS_OPT1 (generated by scripts/analysis/opt1_numbers.py)\n')
print('## Table 3: test set, 3 seeds (mean, sd); val = best-epoch val mean R2 per seed')
rows = {}
for run in ['rn_base', 'rn_mis', 'rn_noprof', 'rn_misnp', 'base', 'mis', 'noprof', 'rn_nolate', 'rn_nolatenp']:
    try:
        t = test(run)
    except FileNotFoundError:
        print(f'- {run}: missing'); continue
    d = {k: ms([x[k] for x in t]) for k in ['r2_s1', 'r2_s2', 'r2_d1', 'r2_d2', 'r2_mean', 'trace_rmse', 'logamp_rmse']}
    rows[run] = (t, d)
    val = []
    for s in (1, 2, 3):
        r = list(csv.DictReader(open(f'{E}/{run}_s{s}/log.csv')))
        val.append(max(float(x['val_r2_mean']) for x in r))
    print(f"- {run}: " + ' '.join(f"{k[3:] if k.startswith('r2') else k} {d[k][0]:.4f}±{d[k][1]:.4f}" for k in d)
          + f" | val {'/'.join(f3(v) for v in val)}")


def paired(a, b, k):
    return [rows[a][0][i][k] - rows[b][0][i][k] for i in range(3)]


print('\n## Paired differences (per seed)')
for a, b in [('rn_misnp', 'rn_noprof'), ('rn_noprof', 'rn_base'), ('rn_mis', 'rn_base'), ('rn_noprof', 'rn_nolatenp'), ('rn_base', 'rn_nolate'), ('noprof', 'base'), ('rn_noprof', 'noprof')]:
    if a in rows and b in rows:
        print(f'- {a} - {b}: ' + ' '.join(f"{k} {[round(x, 4) for x in paired(a, b, k)]}" for k in ['r2_mean', 'r2_s2', 'r2_d2', 'trace_rmse', 'logamp_rmse']))
for a, b in [('rn_misnp', 'rn_noprof'), ('rn_mis', 'rn_base'), ('mis', 'base')]:
    if a in rows and b in rows:
        print(f"- misfit reduction {a} vs {b}: trace {100 * (1 - rows[a][1]['trace_rmse'][0] / rows[b][1]['trace_rmse'][0]):.1f}% "
              f"logamp {100 * (1 - rows[a][1]['logamp_rmse'][0] / rows[b][1]['logamp_rmse'][0]):.1f}%")

print('\n## Noise robustness (n1_u1, r2_mean over seeds; max seed sd)')
N = {t: J(f'{A}/n1_u1/n1_u1_{t}.json')['conditions'] for t in ['rn_noprof', 'rn_misnp', 'noprof', 'rn_base_tm', 'rn_mis_tm']}
for c in N['rn_noprof']:
    print(f'- {c}: ' + ' | '.join(f"{t} " + '/'.join(f3(x) for x in N[t][c]['r2_mean']) + f" (sd<= {max(N[t][c]['r2_sd']):.3f})" for t in ['rn_noprof', 'rn_misnp', 'noprof']))
inr = ['clean', 'snr40', 'snr30', 'snr20', 'gain1', 'gain2', 'gain5', 'snr30_gain2']
gaps = [(abs(N['rn_noprof'][c]['r2_mean'][i] - N['rn_misnp'][c]['r2_mean'][i]), c, NM[i]) for c in inr for i in range(4)]
print('- max |noprof - misnp| inside training range:', max(gaps))
print('- mean R2 per condition noprof/misnp:', {c: (f3(st.mean(N['rn_noprof'][c]['r2_mean'])), f3(st.mean(N['rn_misnp'][c]['r2_mean']))) for c in N['rn_noprof']})
print('- max seed sd rn_noprof snr40-20:', max(max(N['rn_noprof'][c]['r2_sd']) for c in ['snr40', 'snr30', 'snr20']),
      'gains:', max(max(N['rn_noprof'][c]['r2_sd']) for c in ['gain1', 'gain2', 'gain5']),
      'noprof(orig noise) max sd:', max(max(N['noprof'][c]['r2_sd']) for c in inr))

print('\n## UQ rn_noprof, 95% (picp/mpiw per param s1,s2,d1,d2)')
for lev in ['0.95', '0.68']:
    for m in ['mcdropout_gauss', 'ensemble_gauss', 'conformal_clean', 'conformal_trainmix', 'conformal_same_condition']:
        print(f'- {lev} {m}: ' + ' | '.join(
            f"{c} " + ' '.join(f"{p:.2f}/{w:.2f}" for p, w in zip(N['rn_noprof'][c]['uq'][lev][m]['picp'], N['rn_noprof'][c]['uq'][lev][m]['mpiw']))
            for c in ['clean', 'snr40', 'snr30', 'snr20', 'gain2', 'gain5']))

print('\n## Step-off conversion (td_conversion_noprof, 5000 samples, r2_mean s1,s2,d1,d2)')
T = J(f'{A}/td_conversion_noprof/td_conversion.json')
print('- checks', T['checks'])
for k, v in T['conditions'].items():
    print(f'- {k}: ' + '/'.join(f3(x) for x in v['r2_mean']))

print('\n## O1 shifted distributions (per seed)')
for t in ['rn_noprof', 'rn_misnp']:
    O = J(f'{A}/o1/o1_{t}.json')['per_run']
    for run, d in O.items():
        print(f"- {run}: ref rmse {d['ref']['rmse']} | shelf r2 {d['shelf']['r2']} rmse {d['shelf']['rmse']} auc {d['shelf']['auc_vs_ref']:.3f} sp {d['shelf']['spearman_misfit_vs_error']:.2f}"
              f" | extrap rmse {d['extrap']['rmse']} auc {d['extrap']['auc_vs_ref']:.3f} sp {d['extrap']['spearman_misfit_vs_error']:.2f} | ref sp {d['ref']['spearman_misfit_vs_error']:.2f} | pooled sp {d['spearman_misfit_vs_error_pooled']:.2f}")

print('\n## O2 three-layer (per seed; file mtime shown)')
for t in ['rn_noprof', 'rn_misnp']:
    f = f'{A}/o2/o2_{t}.json'; O = J(f)
    print(f'- {t} file {os.path.getmtime(f):.0f} layer_effect {O["layer_effect"]}')
    for run, d in O['per_run'].items():
        print(f"  - {run}: control r2 {d['control']['r2']} rmse {d['control']['rmse']} trace {d['control']['trace_rmse']:.4f} logamp {d['control']['logamp_rmse']:.4f}"
              f" | 3L r2 {d['three_layer']['r2']} rmse {d['three_layer']['rmse']} trace {d['three_layer']['trace_rmse']:.4f} logamp {d['three_layer']['logamp_rmse']:.4f} | auc {d['auc_3L_vs_control']:.3f}")

print('\n## C1 conventional (200 samples, rn_noprof_s1 network + WS rows; LM/L-BFGS-B rows from full_n200_rn*)')
for tag, old in [('noprof_n200_rn', 'full_n200_rn'), ('noprof_n200_rn_snr40', 'full_n200_rn_snr40'), ('noprof_n200_rn_snr40_reg', 'full_n200_rn_snr40_reg')]:
    S = J(f'{A}/c1/{tag}/c1_summary.json'); So = J(f'{A}/c1/{old}/c1_summary.json')
    print(f"- {tag}: net cpu ms {S['dualtcn_cpu_ms_per_sample']}")
    for src, SS in (('new', S), ('old', So)):
        for m, v in SS['methods'].items():
            print(f"  - [{src}] {m}: r2 {v['r2']} mean {v['r2_mean']:.3f} trace {v['trace_rmse']:.2e} logamp {v['logamp_rmse']:.2e} time {v.get('time_mean_s', float('nan')):.1f} s nfev {v.get('nfev_mean', float('nan'))} out {v.get('frac_theta_outside_01')}")
o = J(f'{A}/c1/full_n200_rn/c1_per_sample.json'); n = J(f'{A}/c1/noprof_n200_rn/c1_per_sample.json')
assert o['idx'] == n['idx']
ws = mid = 0; al = []
for ro, rn in zip(o['results'], n['results']):
    g = min(min(ro['LM']['obj_starts']), min(rn['WS-LM']['obj_starts']))
    ok = lambda x: x <= g * 1.01
    ws += ok(rn['WS-LM']['obj_starts'][0]); mid += ok(ro['LM']['obj_starts'][0]); al += [ok(x) for x in ro['LM']['obj_starts']]
print(f'- single start within 1% of the lowest objective (clean): network {ws / 2:.1f}% midpoint {mid / 2:.1f}% all LM starts {100 * sum(al) / len(al):.1f}%')
